/**
 * Icono pixel-art de alta resolución (16x16 / 8x8 adaptable):
 * Cada carácter representa un píxel con soporte de capas y colores.
 *
 *  '#' píxel pleno · 'x' 78% · '+' 50% · '-' 30% · 'a' acento · '.' vacío
 */
data class PixelArt(val rows: List<String>)

@Composable
fun PixelIcon(
    art: PixelArt,
    modifier: Modifier = Modifier,
    size: Dp = 16.dp,
    tint: Color = Color.White,
    accent: Color? = null,
    animate: Boolean = true
) {
    val phase = remember(art) { (art.rows.hashCode() and 0x7FFF) % 1000 / 1000f }
    val breath = rememberInfiniteTransition(label = "pixelIcon")
    val wave by breath.animateFloat(
        initialValue = 0f,
        targetValue = 1f,
        animationSpec = infiniteRepeatable(
            animation = tween(
                durationMillis = 1600 + (phase * 600).toInt(),
                delayMillis = (phase * 400).toInt(),
                easing = FastOutSlowInEasing
            ),
            repeatMode = RepeatMode.Reverse
        ),
        label = "pixelIconWave"
    )
    val bob = with(LocalDensity.current) { 1.dp.toPx() }

    Canvas(
        modifier
            .size(size)
            .graphicsLayer {
                if (animate) {
                    translationY = -bob * wave
                    val scale = 1f + 0.05f * wave
                    scaleX = scale
                    scaleY = scale
                }
            }
    ) {
        val rows = art.rows.size
        val cols = art.rows.maxOfOrNull { it.length } ?: 0
        if (rows == 0 || cols == 0) return@Canvas

        val cell = floor(min(this.size.width / cols, this.size.height / rows)).coerceAtLeast(1f)
        val originX = (this.size.width - cell * cols) / 2f
        val originY = (this.size.height - cell * rows) / 2f

        for (y in art.rows.indices) {
            val row = art.rows[y]
            for (x in 0 until cols) {
                val char = row.getOrElse(x) { '.' }
                val color = when (char) {
                    '#' -> tint
                    'x' -> tint.copy(alpha = 0.78f)
                    '+' -> tint.copy(alpha = 0.5f)
                    '-' -> tint.copy(alpha = 0.3f)
                    'a' -> accent ?: Color(0xFFE8C069)
                    else -> null
                } ?: continue
                drawRect(
                    color = color,
                    topLeft = Offset(originX + x * cell, originY + y * cell),
                    size = Size(cell, cell)
                )
            }
        }
    }
}

